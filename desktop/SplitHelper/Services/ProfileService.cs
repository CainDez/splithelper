    public bool IsManagedActive(string provider)
    {
        var path = Path.Combine(environment.ClashHome, "profiles.yaml");
        if (!File.Exists(path)) return false;
        var root = Parse(File.ReadAllText(path));
        if (Value(root, "current") != ProfileUid(provider)) return false;
        return (Node(root, "items") as YamlSequenceNode)?.Children.OfType<YamlMappingNode>().Any(item => Value(item, "uid") == ProfileUid(provider) && Value(item, "desc") == Ownership && Value(item, "file") == ProfileUid(provider) + ".yaml") == true;
    }
    public bool ProxyGuardDisabled() => ProxyManagementIssue() is null;
    public string? ProxyManagementIssue()
    {
        var path = Path.Combine(environment.ClashHome, "verge.yaml");
        if (!File.Exists(path)) return "未找到 Clash 设置，无法确认代理管理归属；请先完成环境检查和配置导入。";
        try
        {
            var map = Parse(File.ReadAllText(path));
            var enabled = new List<string>();
            foreach (var (key, name) in new[] { ("enable_system_proxy", "系统代理"), ("enable_proxy_guard", "代理守卫"), ("proxy_auto_config", "自动代理（PAC）") })
            {
                var node = Node(map, key);
                if (node is null) continue;
                if (node is not YamlScalarNode scalar) return "Clash 的代理管理设置无法识别，请检查设置后重新导入配置。";
                var value = scalar.Value;
                if (value is null || (scalar.Style == ScalarStyle.Plain && (value.Length == 0 || value == "~" || string.Equals(value, "null", StringComparison.OrdinalIgnoreCase)))) continue;
                if (scalar.Style != ScalarStyle.Plain || !bool.TryParse(value, out var active)) return "Clash 的代理管理设置无法识别，请检查设置后重新导入配置。";
                if (active) enabled.Add(name);
            }
            return enabled.Count == 0 ? null : $"Clash 的{string.Join("、", enabled)}仍开启，会与分流助手的代理管理冲突，自动启用检查无法通过。请先停止分流，在 Clash 设置中关闭上述开关，再回助手重新检测并启用。";
        }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException or YamlException or UserError)
        { return "无法读取 Clash 的代理管理设置，请检查设置文件后重新导入配置。"; }
    }
    public bool RuntimeDnsMatches(string provider)
    {
        var path = Path.Combine(environment.ClashHome, "clash-verge.yaml");
        if (!File.Exists(path)) return false;
        var map = Parse(File.ReadAllText(path));
        var dns = Node(map, "dns") as YamlMappingNode;
        if (dns is null || Node(dns, "nameserver") is not YamlSequenceNode servers || !servers.Children.OfType<YamlScalarNode>().Any(node => node.Value == $"https://1.1.1.1/dns-query#{provider}")) return false;
        var policy = Node(dns, "nameserver-policy") as YamlMappingNode;
        if (policy is null || Node(policy, "geosite:cn") is not YamlSequenceNode china || !china.Children.OfType<YamlScalarNode>().Any(node => node.Value == "https://223.5.5.5/dns-query#ChinaDirect")) return false;
        return provider != "Windscribe" || (Value(map, "find-process-mode") == "strict" && Node(map, "interface-name") is null);
    }
