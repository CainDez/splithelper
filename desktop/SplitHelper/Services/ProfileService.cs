    private static readonly JsonSerializerOptions CustomRulesJson = new() { PropertyNameCaseInsensitive = true, WriteIndented = true };
    public const string Ownership = "Managed by SplitHelper Desktop v1";
    public static string ProfileUid(string provider) => "splithelper-" + provider.ToLowerInvariant() + "-v1";
    public static string ScriptUid(string provider) => ProfileUid(provider) + "-dns";
    public static YamlMappingNode Parse(string text)
    {
        var stream = new YamlStream();
        stream.Load(new StringReader(text));
        return stream.Documents.Count == 1 && stream.Documents[0].RootNode is YamlMappingNode map ? map : throw new UserError("配置文件格式不正确，未作任何修改。");
    }
    public static string Dump(YamlMappingNode map)
    {
        var writer = new StringWriter(System.Globalization.CultureInfo.InvariantCulture);
        new YamlStream(new YamlDocument(map)).Save(writer, false);
        return writer.ToString();
    }
    public static YamlNode? Node(YamlMappingNode map, string key) => map.Children.TryGetValue(new YamlScalarNode(key), out var value) ? value : null;
    public static string? Value(YamlMappingNode map, string key) => (Node(map, key) as YamlScalarNode)?.Value;
    public static void Set(YamlMappingNode map, string key, string value, bool quoted = false) => map.Children[new YamlScalarNode(key)] = new YamlScalarNode(value) { Style = quoted ? ScalarStyle.DoubleQuoted : ScalarStyle.Any };
    public static string Resource(string name)
    {
        using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream(name) ?? throw new InvalidOperationException("Bundled template missing.");
        using var reader = new StreamReader(stream, Encoding.UTF8);
        return reader.ReadToEnd();
    }
    public static void Validate(AppSettings settings)
    {
        if (settings.Provider is not ("Mullvad" or "Windscribe")) throw new UserError("请选择 Mullvad 或 Windscribe。");
        if (settings.MixedPort is < 1 or > 65535 || settings.MixedPort == 18997) throw new UserError("Clash 混合端口须为 1–65535，且不能与内置组件端口 18997 相同。");
        if (settings.Provider != "Windscribe") return;
        var parts = settings.GatewayHost.Split('.');
        if (parts.Length != 4 || parts.Any(part => !byte.TryParse(part, out var number) || number.ToString() != part)) throw new UserError("请填写 Windscribe 网关界面显示的 IPv4 地址。");
        if (settings.GatewayHost.StartsWith("192.0.2.", StringComparison.Ordinal) || settings.GatewayHost.StartsWith("198.51.100.", StringComparison.Ordinal) || settings.GatewayHost.StartsWith("203.0.113.", StringComparison.Ordinal)) throw new UserError("不能使用文档示例网关地址，请填写本机实际网关地址。");
        if (settings.GatewayPort is < 1 or > 65535) throw new UserError("网关端口须为 1–65535。");
        if (string.IsNullOrWhiteSpace(settings.GatewayUsername) || string.IsNullOrEmpty(settings.GatewayPassword)) throw new UserError("请填写网关用户名和密码，不是 Windscribe 账号密码。");
    }
    public static string Generate(AppSettings settings, bool redact = false)
    {
        Validate(settings);
        var map = Parse(Resource($"Templates.{settings.Provider}.yaml"));
        Set(map, "mixed-port", settings.MixedPort.ToString());
        if (settings.Provider == "Windscribe")
        {
            var proxies = (YamlSequenceNode)Node(map, "proxies")!;
            var official = proxies.Children.OfType<YamlMappingNode>().Single(proxy => Value(proxy, "name") == "Official");
            Set(official, "server", settings.GatewayHost, true);
            Set(official, "port", settings.GatewayPort.ToString());
            Set(official, "username", redact ? "[已隐藏]" : settings.GatewayUsername, true);
            Set(official, "password", redact ? "[已隐藏]" : settings.GatewayPassword, true);
        }
        return "# Generated by SplitHelper. Keep credentials on this computer.\n" + Dump(map);
    }
    public static void ValidateStandalone(AppSettings settings)
    {
        if (settings.Provider is not ("Mullvad" or "Windscribe")) throw new UserError("请选择 Mullvad 或 Windscribe。");
        if (settings.MixedPort is < 1 or > 65535 || settings.MixedPort == 18997) throw new UserError("混合端口须为 1–65535，且不能与内置组件端口 18997 相同。");
        if (settings.Provider == "Windscribe" && settings.WindscribeInterface is not ("" or "Windscribe IKEv2" or "WindscribeWireguard")) throw new UserError("尚未识别到受支持的 Windscribe VPN 接口，请使用 IKEv2 或 WireGuard 连接。");
    }
    public static CustomRule[] NormalizeCustomRules(IReadOnlyList<CustomRule> rules)
    {
        var normalized = new CustomRule[rules.Count];
        var scopes = new HashSet<(string Domain, bool IncludeSubdomains)>();
        for (var index = 0; index < rules.Count; index++)
        {
            var rule = rules[index];
            if (rule is null) throw new UserError($"第 {index + 1} 条自定义规则为空。");
            if (rule.Target is not ("ChinaDirect" or "VPN" or "REJECT")) throw new UserError($"第 {index + 1} 条自定义规则的策略无效。");
            var domain = NormalizeDomain(rule.Domain) ?? throw new UserError($"第 {index + 1} 条规则需要有效域名或 HTTP(S) 网址。");
            if (!scopes.Add((domain, rule.IncludeSubdomains))) throw new UserError($"第 {index + 1} 条规则与已有规则的域名和匹配范围重复。");
            normalized[index] = rule with { Domain = domain };
        }
        return normalized;
    }

    private static string? NormalizeDomain(string? input)
    {
        if (string.IsNullOrWhiteSpace(input) || input.IndexOfAny(['\\', '\r', '\n', '\u0085', '\u2028', '\u2029']) >= 0 || input.Any(char.IsControl)) return null;
        var host = input.Trim();
        if (host.StartsWith("http://", StringComparison.OrdinalIgnoreCase) || host.StartsWith("https://", StringComparison.OrdinalIgnoreCase))
        {
            if (!Uri.TryCreate(host, UriKind.Absolute, out var uri) || uri.HostNameType != UriHostNameType.Dns) return null;
            host = uri.Host;
        }
        try
        {
            var idn = new IdnMapping { UseStd3AsciiRules = true };
            host = idn.GetAscii(host).ToLowerInvariant();
            if (host.EndsWith('.')) host = host[..^1];
            if (host.Length > 253 || IPAddress.TryParse(host, out _)) return null;
            var labels = host.Split('.');
            if (labels.Length < 2 || !labels[^1].Any(char.IsAsciiLetter)) return null;
            if (labels.Any(label => label.Length is < 1 or > 63 || label[0] == '-' || label[^1] == '-' || label.Any(c => !char.IsAsciiLetterOrDigit(c) && c != '-'))) return null;
            // Validate already-punycoded input as well as Unicode input.
            _ = idn.GetUnicode(host);
            return host;
        }
        catch (ArgumentException) { return null; }
    }

    public CustomRule[] LoadCustomRules()
    {
        try
        {
            var rules = JsonSerializer.Deserialize<CustomRule[]>(File.ReadAllText(paths.CustomRulesFile), CustomRulesJson)
                ?? throw new UserError("已保存的自定义规则文件为空，请检查 custom-rules.json。");
            return NormalizeCustomRules(rules);
        }
        catch (FileNotFoundException) { return []; }
        catch (DirectoryNotFoundException) { return []; }
        catch (JsonException) { throw new UserError("已保存的自定义规则文件损坏，请检查 custom-rules.json。"); }
    }

    internal static string SerializeCustomRules(IReadOnlyList<CustomRule> rules) => JsonSerializer.Serialize(rules, CustomRulesJson);
    internal static string StandaloneVpnProxy(string provider) => provider == "Windscribe" ? "VPNDirect" : "Official";
    internal static string CustomRuleProxy(string provider, CustomRule rule) => rule.Target == "VPN" ? StandaloneVpnProxy(provider) : rule.Target;

    public static string GenerateStandalone(AppSettings settings, string pipeName, IReadOnlyList<string>? preservedRules = null, IReadOnlyList<CustomRule>? customRules = null)
    {
        var map = BuildStandalone(settings, pipeName, preservedRules);
        if (customRules is not null) AddCustomRules(map, settings.Provider, NormalizeCustomRules(customRules));
        return DumpStandalone(map);
    }

    private static YamlMappingNode BuildStandalone(AppSettings settings, string pipeName, IReadOnlyList<string>? preservedRules)
    {
        ValidateStandalone(settings);
        if (string.IsNullOrWhiteSpace(pipeName) || pipeName.IndexOfAny(['\\', '/', ':']) >= 0) throw new UserError("主内核控制管道名称无效。");
        var map = Parse(Resource($"Templates.{settings.Provider}.yaml"));
        Set(map, "mixed-port", settings.MixedPort.ToString());
        Set(map, "mode", "rule"); Set(map, "ipv6", "false"); Set(map, "allow-lan", "false"); Set(map, "bind-address", "127.0.0.1");
        Set(map, "external-controller-pipe", @"\\.\pipe\" + pipeName, true);
        // SplitHelper schedules the controller update so a failed first download can be retried.
        Set(map, "geodata-mode", "false"); Set(map, "geo-auto-update", "false");
        const string geoRelease = "https://github.com/MetaCubeX/meta-rules-dat/releases/download/latest/";
        map.Children[new YamlScalarNode("geox-url")] = new YamlMappingNode
        {
            { "geosite", geoRelease + "geosite.dat" },
            { "mmdb", geoRelease + "country.mmdb" }
        };
        var dns = (YamlMappingNode)Node(map, "dns")!;
        dns.Children.Remove(new YamlScalarNode("listen"));
        var overseas = settings.Provider == "Windscribe" ? "VPNDirect" : "Mullvad";
        dns.Children[new YamlScalarNode("nameserver")] = new YamlSequenceNode(new YamlScalarNode($"https://1.1.1.1/dns-query#{overseas}"));
        if (settings.Provider == "Windscribe")
        {
            var proxies = (YamlSequenceNode)Node(map, "proxies")!;
            var official = proxies.Children.OfType<YamlMappingNode>().Single(proxy => Value(proxy, "name") == "Official");
            proxies.Children.Remove(official);
            proxies.Children.Insert(0, new YamlMappingNode
            {
                { "name", "VPNDirect" }, { "type", "direct" }, { "interface-name", string.IsNullOrEmpty(settings.WindscribeInterface) ? "Windscribe IKEv2" : settings.WindscribeInterface }, { "ip-version", "ipv4" }
            });
            var group = ((YamlSequenceNode)Node(map, "proxy-groups")!).Children.OfType<YamlMappingNode>().Single();
            group.Children[new YamlScalarNode("proxies")] = new YamlSequenceNode(new YamlScalarNode("VPNDirect"));
        }
        var rules = preservedRules ?? ((YamlSequenceNode)Node(map, "rules")!).Children.Cast<YamlScalarNode>().Select(rule => rule.Value ?? "").ToArray();
        if (rules.Count == 0) throw new UserError("待迁移规则为空，请检查原配置。");
        var converted = new YamlSequenceNode();
        foreach (var rule in rules)
        {
            var parts = rule.Split(',').Select(part => part.Trim()).ToArray();
            if (parts.Length < 2 || parts.Any(string.IsNullOrEmpty)) throw new UserError("存在无法迁移的规则，请检查原配置。");
            parts[0] = parts[0].ToUpperInvariant();
            if (parts[0] is "RULE-SET" or "SUB-RULE") throw new UserError("独立主内核不支持迁移外部规则集或子规则，请先将其转换为普通规则。");
            // Match Mihomo 1.19.33 ParseRulePayload: ordinary rules can have parameters after the policy.
            var policyIndex = parts[0] switch { "MATCH" => 1, "NOT" or "OR" or "AND" or "DOMAIN-REGEX" or "PROCESS-NAME-REGEX" or "PROCESS-PATH-REGEX" => parts.Length - 1, _ => 2 };
            if (policyIndex >= parts.Length) throw new UserError("规则缺少策略，请检查原配置。");
            var policy = parts[policyIndex];
            if (policy is not ("DIRECT" or "REJECT" or "REJECT-DROP" or "ChinaDirect" or "Official" or "VPNDirect") && policy != settings.Provider)
                throw new UserError($"规则策略“{policy}”不受独立主内核支持，请先调整原配置。");
            if (settings.Provider == "Mullvad" && policy == "VPNDirect") throw new UserError("Mullvad 配置不能使用 Windscribe 的 VPNDirect 策略。");
            if (settings.Provider == "Windscribe" && parts.Length == 3 && parts[0] == "PROCESS-NAME" && string.Equals(parts[1], "Windscribe.exe", StringComparison.OrdinalIgnoreCase) && policy == "DIRECT") continue;
            if (settings.Provider == "Windscribe" && policy == "Official") parts[policyIndex] = "VPNDirect";
            converted.Add(string.Join(',', parts));
        }
        var finalRules = converted.Children.Cast<YamlScalarNode>().Select(rule => rule.Value!.Split(',')).ToArray();
        var fallback = StandaloneVpnProxy(settings.Provider);
        if (finalRules.Length == 0 || finalRules.Count(rule => rule[0] == "MATCH") != 1 || finalRules[^1].Length != 2 || finalRules[^1][0] != "MATCH" || (finalRules[^1][1] != settings.Provider && finalRules[^1][1] != fallback))
            throw new UserError("迁移规则必须只有一个位于末尾、指向当前 VPN 的 MATCH 规则；缺省直连或 MATCH,DIRECT 无法保证断线保护。已保留原规则，请先调整后重试。");
        map.Children[new YamlScalarNode("rules")] = converted;
        return map;
    }

    private static string DumpStandalone(YamlMappingNode map) => "# Managed by SplitHelper. Private standalone main core.\n" + Dump(map);

    private static void AddCustomRules(YamlMappingNode map, string provider, IReadOnlyList<CustomRule> customRules)
    {
        var rules = (YamlSequenceNode)Node(map, "rules")!;
        var index = 0;
        foreach (var rule in customRules)
        {
            if (!rule.Enabled) continue;
            var type = rule.IncludeSubdomains ? "DOMAIN-SUFFIX" : "DOMAIN";
            rules.Children.Insert(index++, new YamlScalarNode($"{type},{rule.Domain},{CustomRuleProxy(provider, rule)}"));
        }
    }
    public static AppSettings ReadStandaloneSettings(string path)
    {
        if (!File.Exists(path)) throw new UserError("独立主内核配置不存在，请先停止并还原旧会话后重新启用。");
        var map = Parse(File.ReadAllText(path));
        var group = (Node(map, "proxy-groups") as YamlSequenceNode)?.Children.OfType<YamlMappingNode>().SingleOrDefault();
        var vpn = (Node(map, "proxies") as YamlSequenceNode)?.Children.OfType<YamlMappingNode>().SingleOrDefault(proxy => Value(proxy, "name") == "VPNDirect");
        if (!int.TryParse(Value(map, "mixed-port"), out var port)) throw new UserError("独立主内核端口配置无效。");
        var settings = new AppSettings { Provider = group is null ? "" : Value(group, "name") ?? "", MixedPort = port, WindscribeInterface = vpn is null ? "" : Value(vpn, "interface-name") ?? "" };
        ValidateStandalone(settings);
        return settings;
    }
    // Snapshot the confirmed active rules once; subsequent preparations never re-import Clash changes.
    public string PrepareStandalone(AppSettings settings) => PrepareStandalone(settings, LoadCustomRules());

    public string RenderStandalone(AppSettings settings)
    {
        ValidateStandalone(settings);
        var map = BuildStandalone(settings, paths.MainPipeName, ReadStandaloneBaseRules(settings.Provider));
        AddCustomRules(map, settings.Provider, LoadCustomRules());
        return DumpStandalone(map);
    }

    internal string PrepareStandalone(AppSettings settings, IReadOnlyList<CustomRule> customRules)
    {
        ValidateStandalone(settings);
        var snapshot = StandaloneRuleSnapshot(settings.Provider);
        var generated = BuildStandalone(settings, paths.MainPipeName, ReadStandaloneBaseRules(settings.Provider));
        Directory.CreateDirectory(paths.MainRuntimeDirectory);
        if (!File.Exists(snapshot))
        {
            var saved = new YamlMappingNode { { "rules", Node(generated, "rules")! } };
            SettingsStore.AtomicWrite(snapshot, Dump(saved));
        }
        AddCustomRules(generated, settings.Provider, customRules);
        SettingsStore.AtomicWrite(paths.MainConfig, DumpStandalone(generated));
        return paths.MainConfig;
    }

    private string StandaloneRuleSnapshot(string provider) => Path.Combine(paths.MainRuntimeDirectory, $"rules-{provider}.yaml");

    private IReadOnlyList<string>? ReadStandaloneBaseRules(string provider)
    {
        var snapshot = StandaloneRuleSnapshot(provider);
        if (File.Exists(snapshot)) return ReadStandaloneRules(File.ReadAllText(snapshot));
        if (!IsManagedActive(provider)) return null;
        var active = Path.Combine(environment.ClashHome, "clash-verge.yaml");
        if (!File.Exists(active)) throw new UserError("已确认的 Clash 活动配置不存在，无法迁移规则。");
        return ReadStandaloneRules(File.ReadAllText(active));
    }

    internal static IReadOnlyList<string> ReadStandaloneRules(string text)
    {
        if (Node(Parse(text), "rules") is not YamlSequenceNode rules || rules.Children.Any(rule => rule is not YamlScalarNode)) throw new UserError("活动配置规则格式无效，未迁移或覆盖规则。");
        return rules.Children.Cast<YamlScalarNode>().Select(rule => rule.Value ?? "").ToArray();
    }
    public string WriteGenerated(AppSettings settings)
    {
        Directory.CreateDirectory(paths.GeneratedDirectory);
        var target = Path.Combine(paths.GeneratedDirectory, $"Clash-{settings.Provider}.local.yaml");
        SettingsStore.AtomicWrite(target, Generate(settings));
        SettingsStore.AtomicWrite(Path.Combine(paths.GeneratedDirectory, $"Profile-DNS-{settings.Provider}.js"), Resource($"Templates.{settings.Provider}.js"));
        return target;
    }
    public static string MergeMetadata(string original, string provider)
    {
        var root = Parse(original);
        if (Node(root, "items") is not YamlSequenceNode items)
        {
            items = new YamlSequenceNode();
            root.Children[new YamlScalarNode("items")] = items;
        }
        foreach (var (uid, type, file) in new[] { (ProfileUid(provider), "local", ProfileUid(provider) + ".yaml"), (ScriptUid(provider), "script", ScriptUid(provider) + ".js") })
        {
            var matches = items.Children.OfType<YamlMappingNode>().Where(item => Value(item, "uid") == uid).ToList();
            if (matches.Count > 1 || matches.Any(item => Value(item, "desc") != Ownership || Value(item, "file") != file)) throw new UserError("发现同名但不属于本助手的配置，已保留原文件，请在诊断中处理冲突。");
            var item = matches.SingleOrDefault() ?? new YamlMappingNode();
            Set(item, "uid", uid); Set(item, "type", type); Set(item, "file", file); Set(item, "name", type == "local" ? $"分流助手 · {provider}" : $"分流助手 · {provider} DNS", true);
            Set(item, "desc", Ownership, true); Set(item, "updated", DateTimeOffset.UtcNow.ToUnixTimeSeconds().ToString());
            if (type == "local")
            {
                var option = Node(item, "option") as YamlMappingNode ?? new YamlMappingNode();
                Set(option, "script", ScriptUid(provider));
                item.Children[new YamlScalarNode("option")] = option;
            }
            if (matches.Count == 0) items.Add(item);
        }
        Set(root, "current", ProfileUid(provider));
        return Dump(root);
    }
    public string Import(AppSettings settings)
    {
        Validate(settings);
        if (!environment.SupportsImport) throw new UserError("当前自动导入适配 Clash Verge Rev 2.4.7；其他版本请先使用导出配置功能。");
        if (ClientEnvironment.ClashIsRunning) throw new UserError("请先从 Clash Verge 托盘菜单选择“退出”，再点导入。仅关闭窗口不会退出；后台服务可保持运行。");
        var home = environment.ClashHome;
        var metadata = Path.Combine(home, "profiles.yaml");
        var config = Path.Combine(home, "config.yaml");
        var verge = Path.Combine(home, "verge.yaml");
        if (!new[] { metadata, config, verge }.All(File.Exists)) throw new UserError("请先打开一次 Clash Verge 完成初始化，然后从托盘退出再导入。");
        var originals = new[] { metadata, config, verge }.ToDictionary(path => path, File.ReadAllText, StringComparer.OrdinalIgnoreCase);
        var baseConfig = Parse(originals[config]); var appConfig = Parse(originals[verge]);
        Set(baseConfig, "mode", "rule"); Set(baseConfig, "ipv6", "false");
        Set(appConfig, "enable_tun_mode", "false"); Set(appConfig, "enable_system_proxy", "false"); Set(appConfig, "enable_proxy_guard", "false"); Set(appConfig, "verge_mixed_port", settings.MixedPort.ToString());
        var profilePath = Path.Combine(home, "profiles", ProfileUid(settings.Provider) + ".yaml");
        var scriptPath = Path.Combine(home, "profiles", ScriptUid(settings.Provider) + ".js");
        var existingItems = Node(Parse(originals[metadata]), "items") as YamlSequenceNode;
        foreach (var (uid, file) in new[] { (ProfileUid(settings.Provider), profilePath), (ScriptUid(settings.Provider), scriptPath) })
        {
            if (File.Exists(file) && existingItems?.Children.OfType<YamlMappingNode>().Any(item => Value(item, "uid") == uid && Value(item, "desc") == Ownership && Value(item, "file") == Path.GetFileName(file)) != true) throw new UserError("目标配置文件已存在但无法确认归属，本次没有覆盖它。");
        }
        var backup = Path.Combine(paths.DataDirectory, "clash-backups", DateTime.UtcNow.ToString("yyyyMMdd-HHmmss-ffff"));
        var baselinePath = Path.Combine(paths.DataDirectory, "clash-baseline.dat");
        var baseline = SettingsStore.ReadProtected<SetupBaseline>(baselinePath);
        if (baseline is not null && !string.Equals(baseline.Home, home, StringComparison.OrdinalIgnoreCase)) throw new UserError("Clash 配置目录已改变，请先处理原目录的接管记录。");
        var nextBaseline = baseline is null ? new SetupBaseline(home, backup, settings.MixedPort) : baseline with { Port = settings.MixedPort };
        var outputs = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            [baselinePath] = SettingsStore.ProtectText(JsonSerializer.Serialize(nextBaseline)),
            [profilePath] = Generate(settings), [scriptPath] = Resource($"Templates.{settings.Provider}.js"),
            [config] = Dump(baseConfig), [verge] = Dump(appConfig), [metadata] = MergeMetadata(originals[metadata], settings.Provider)
        };
        Directory.CreateDirectory(backup);
        foreach (var output in outputs.Keys)
        {
            if (File.Exists(output))
            {
                if (!originals.ContainsKey(output)) originals[output] = File.ReadAllText(output);
                File.Copy(output, Path.Combine(backup, Path.GetFileName(output)), false);
            }
        }
        if (ClientEnvironment.ClashIsRunning) throw new UserError("Clash GUI 已重新运行，本次没有导入，请退出后重试。");
        WriteWithRollback(outputs, originals);
        return backup;
    }
    public void RemoveManagedSetup()
    {
        var baselinePath = Path.Combine(paths.DataDirectory, "clash-baseline.dat");
        var baseline = SettingsStore.ReadProtected<SetupBaseline>(baselinePath);
        if (baseline is null) return;
        if (ClientEnvironment.ClashIsRunning) throw new UserError("请先从 Clash 托盘退出 GUI，再还原旧版导入记录，避免配置缓存覆盖还原结果。");
        if (!string.Equals(baseline.Home, environment.ClashHome, StringComparison.OrdinalIgnoreCase)) throw new UserError("Clash 配置目录与接管记录不一致，未执行卸载清理。");
        var metadataPath = Path.Combine(baseline.Home, "profiles.yaml");
        var configPath = Path.Combine(baseline.Home, "config.yaml");
        var vergePath = Path.Combine(baseline.Home, "verge.yaml");
        if (!new[] { metadataPath, configPath, vergePath }.All(File.Exists)) throw new UserError("Clash 配置不完整，保留接管记录，请先恢复配置后卸载。");
        var originalMetadata = Parse(File.ReadAllText(Path.Combine(baseline.Backup, "profiles.yaml")));
        var originalConfig = Parse(File.ReadAllText(Path.Combine(baseline.Backup, "config.yaml")));
        var originalVerge = Parse(File.ReadAllText(Path.Combine(baseline.Backup, "verge.yaml")));
        var currentMetadata = Parse(File.ReadAllText(metadataPath));
        var currentConfig = Parse(File.ReadAllText(configPath)); var currentVerge = Parse(File.ReadAllText(vergePath));
        var removedFiles = new List<string>();
        if (Node(currentMetadata, "items") is YamlSequenceNode items)
        {
            foreach (var provider in new[] { "Mullvad", "Windscribe" })
            {
                foreach (var uid in new[] { ProfileUid(provider), ScriptUid(provider) })
                {
                    var expectedFile = uid + (uid == ProfileUid(provider) ? ".yaml" : ".js");
                    foreach (var item in items.Children.OfType<YamlMappingNode>().Where(item => Value(item, "uid") == uid && Value(item, "desc") == Ownership && Value(item, "file") == expectedFile).ToList()) { items.Children.Remove(item); removedFiles.Add(Path.Combine(baseline.Home, "profiles", expectedFile)); }
                }
            }
            if (new[] { ProfileUid("Mullvad"), ProfileUid("Windscribe") }.Contains(Value(currentMetadata, "current")))
            {
                var previous = Value(originalMetadata, "current");
                if (previous is not null && items.Children.OfType<YamlMappingNode>().Any(item => Value(item, "uid") == previous)) Set(currentMetadata, "current", previous);
                else currentMetadata.Children.Remove(new YamlScalarNode("current"));
            }
        }
        RestoreField(currentConfig, originalConfig, "mode", "rule"); RestoreField(currentConfig, originalConfig, "ipv6", "false");
        foreach (var key in new[] { "enable_tun_mode", "enable_system_proxy", "enable_proxy_guard" }) RestoreField(currentVerge, originalVerge, key, "false");
        RestoreField(currentVerge, originalVerge, "verge_mixed_port", baseline.Port.ToString());
        var updates = new Dictionary<string, string> { [configPath] = Dump(currentConfig), [vergePath] = Dump(currentVerge), [metadataPath] = Dump(currentMetadata) };
        var before = updates.Keys.ToDictionary(path => path, File.ReadAllText);
        WriteWithRollback(updates, before);
        foreach (var file in removedFiles) if (File.Exists(file)) File.Delete(file);
        File.Delete(baselinePath);
    }
    internal static void WriteWithRollback(IReadOnlyDictionary<string, string> outputs, IReadOnlyDictionary<string, string> originals)
    {
        var changed = new List<string>();
        try { foreach (var output in outputs) { SettingsStore.AtomicWrite(output.Key, output.Value); changed.Add(output.Key); } }
        catch
        {
            foreach (var path in changed.AsEnumerable().Reverse()) { if (originals.TryGetValue(path, out var original)) SettingsStore.AtomicWrite(path, original); else File.Delete(path); }
            throw;
        }
    }
    private static void RestoreField(YamlMappingNode current, YamlMappingNode original, string key, string managedValue)
    {
        if (Value(current, key) != managedValue) return;
        if (Node(original, key) is { } prior) current.Children[new YamlScalarNode(key)] = prior;
        else current.Children.Remove(new YamlScalarNode(key));
    }
